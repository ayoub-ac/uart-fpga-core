"""
Generator for tb/random_vectors.h.

The UART testbench uses cross-loopback (TX A -> RX B) to verify
byte-exact round-trip of arbitrary data, so the "reference oracle" is
trivial: the byte that was pushed at side A must be the byte that pops
out of side B. Unlike the cipher cores in this family, there is no
external software model to cross-check against.

This script therefore emits a header with a deterministic pseudo-random
byte stream the C++ harness can consume if it ever wants to replay the
same regression seed across runs. In the current tb/sim_main.cpp the
loopback test generates its own LCG sequence inline, so the header is
optional. Kept for parity with the sibling IP cores.
"""

import sys
import textwrap

N = 1024
SEED = 0xdeadbeef


def lcg(seed: int, n: int):
    s = seed
    out = []
    for _ in range(n):
        s = (s * 1103515245 + 12345) & 0xffff_ffff
        out.append(s & 0xff)
    return out


def main():
    bytes_ = lcg(SEED, N)
    print("// SPDX-License-Identifier: GPL-3.0-or-later OR Commercial")
    print("// AUTO-GENERATED by tb/gen_random_vectors.py — do not edit by hand.")
    print(f"// Seed: 0x{SEED:08x}, length: {N}")
    print()
    print("#pragma once")
    print()
    print("#include <cstdint>")
    print(f"static const uint32_t kRandLen = {N};")
    print("static const uint8_t  kRandBytes[] = {")
    for line in textwrap.wrap(
            ", ".join(f"0x{b:02x}" for b in bytes_), 78):
        print(f"  {line},")
    print("};")


if __name__ == "__main__":
    main()
